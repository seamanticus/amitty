// key matches an Xresources line such as "*.color4: #81a1c1".
var key = regexp.MustCompile(`(?m)^\*(?:\.|\w*\.)?(\w+):\s*#([0-9A-Fa-f]{6})`)

func fetch(name string) (map[string]uint32, error) {
	resp, err := http.Get("https://raw.githubusercontent.com/mbadolato/iTerm2-Color-Schemes/" + commit + "/Xresources/" + url.PathEscape(name))
	if err != nil {
		return nil, err
	}
	defer resp.Body.Close() //nolint:errcheck
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("%s: %s", name, resp.Status)
	}
	body, err := io.ReadAll(resp.Body)
	if err != nil {
		return nil, err
	}
	values := map[string]uint32{}
	for _, m := range key.FindAllStringSubmatch(string(body), -1) {
		v, _ := strconv.ParseUint(m[2], 16, 32)
		values[m[1]] = uint32(v)
	}
	for _, k := range append([]string{"foreground", "background"}, colorKeys()...) {
		if _, ok := values[k]; !ok {
			return nil, fmt.Errorf("%s: no %s", name, k)
		}
	}
	return values, nil
}

func colorKeys() []string {
	keys := make([]string, 16)
	for i := range keys {
		keys[i] = "color" + strconv.Itoa(i)
	}
	return keys
}

func main() {
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by genprofiles/main.go from mbadolato/iTerm2-Color-Schemes at %s (MIT); DO NOT EDIT.\n\npackage config\n\n", commit)
	out.WriteString("// profilePalettes returns the palettes of the theme profiles by name, in maya's curated order.\nfunc profilePalettes() []namedPalette {\n\treturn []namedPalette{\n")
	for _, name := range names {
		v, err := fetch(name)
		if err != nil {
			log.Fatal(err)
		}
		var colors []string
		for _, k := range colorKeys() {
			colors = append(colors, fmt.Sprintf("0x%06x", v[k]))
		}
		fmt.Fprintf(&out, "\t\t{%q, palette{fg: 0x%06x, bg: 0x%06x, colors: [16]uint32{%s}}},\n", name, v["foreground"], v["background"], strings.Join(colors, ", "))
	}
	out.WriteString("\t}\n}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("../profiles.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}
