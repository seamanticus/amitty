//go:build ignore

// Command generator writes docs/config.md and default.toml from the config structs: a heading per table and option, named by its toml key, with its doc comment and default value.
// default.toml has every option commented out under its table, so uncommenting one sets it.
package main

import (
	"bytes"
	"encoding"
	"fmt"
	"go/ast"
	"go/parser"
	"go/token"
	"log"
	"os"
	"path/filepath"
	"reflect"
	"strings"

	"github.com/BurntSushi/toml"
	"github.com/seamanticus/amitty/internal/config"
)

const header = "<!-- Code generated by go generate; DO NOT EDIT. -->\n\n" +
	"# Configuration\n\n" +
	"Every option of `~/.config/amitty/config.toml`, by its TOML key, with its default. The first run writes the file with every option commented out; uncomment one to change it (see [Install and run](install.md)).\n\n"

const footer = "\n<!-- nav -->\n\n---\n\n[Previous: Network and privacy](network.md) | [Contents](README.md) | [Next: Troubleshooting](troubleshooting.md)\n"

const tomlHeader = "# Code generated by go generate; DO NOT EDIT.\n#\n# amitty's configuration with every option at its default, commented out.\n# Uncomment an option to change it. The manual is docs/config.md.\n"

// docs maps "Type.Field" to the doc comment of that struct field.
var docs = map[string]string{}

type field struct {
	key, doc string
	value    reflect.Value
}

// structFields returns the fields of the struct value, with those of embedded structs in place.
func structFields(value reflect.Value) []field {
	var fields []field
	structType := value.Type()
	for index := range structType.NumField() {
		structField := structType.Field(index)
		if structField.Anonymous {
			fields = append(fields, structFields(value.Field(index))...)
			continue
		}

		fields = append(fields, field{structField.Tag.Get("toml"), docs[structType.Name()+"."+structField.Name], value.Field(index)})
	}

	return fields
}

// isTable reports whether value is written as a table rather than as a value.
func isTable(value reflect.Value) bool {
	switch value.Interface().(type) {
	case toml.Marshaler, encoding.TextMarshaler:
		return false
	}

	return value.Kind() == reflect.Struct
}

// write writes a section for each option of the table at path: its doc comment, then its default value or, for a table, its own options.
func write(buffer *bytes.Buffer, path string, table reflect.Value) {
	if path != "" {
		path += "."
	}

	for _, field := range structFields(table) {
		name := path + field.key
		fmt.Fprintf(buffer, "%s %s\n\n", strings.Repeat("#", strings.Count(name, ".")+2), name)
		if field.doc != "" {
			fmt.Fprintf(buffer, "%s\n", field.doc)
		}

		if isTable(field.value) {
			write(buffer, name, field.value)
			continue
		}

		fmt.Fprintf(buffer, "Default: `%s`\n\n", encodeValue(field))
	}
}

// writeTOML writes the options of the table at path, values before subtables as TOML requires, each commented out under its doc comment.
func writeTOML(buffer *bytes.Buffer, path string, table reflect.Value) {
	fields := structFields(table)
	if path != "" {
		fmt.Fprintf(buffer, "[%s]\n", path)
	}
	for _, field := range fields {
		if isTable(field.value) {
			continue
		}
		buffer.WriteString("\n")
		writeComment(buffer, field.doc)
		fmt.Fprintf(buffer, "# %s = %s\n", field.key, encodeValue(field))
	}
	for _, field := range fields {
		if !isTable(field.value) {
			continue
		}
		name := field.key
		if path != "" {
			name = path + "." + field.key
		}
		buffer.WriteString("\n")
		writeComment(buffer, field.doc)
		writeTOML(buffer, name, field.value)
	}
}

// writeComment writes doc as TOML comment lines.
func writeComment(buffer *bytes.Buffer, doc string) {
	for line := range strings.Lines(strings.TrimRight(doc, "\n")) {
		fmt.Fprintf(buffer, "# %s\n", strings.TrimRight(line, "\n"))
	}
}

// encodeValue returns the TOML of field's value. The encoder only writes whole documents, so the value is what follows the key.
func encodeValue(field field) string {
	// The encoder writes a map as a table of its own, which has no value to put after the key.
	if field.value.Kind() == reflect.Map && field.value.Len() == 0 {
		return "{}"
	}
	var line bytes.Buffer
	if err := toml.NewEncoder(&line).Encode(map[string]any{field.key: field.value.Interface()}); err != nil {
		log.Fatal(err)
	}

	_, value, _ := strings.Cut(line.String(), " = ")
	return strings.TrimSpace(value)
}

// collectDocs adds the doc comment of each struct field in file to docs.
func collectDocs(file *ast.File) {
	ast.Inspect(file, func(node ast.Node) bool {
		spec, ok := node.(*ast.TypeSpec)
		if !ok {
			return true
		}

		structType, ok := spec.Type.(*ast.StructType)
		if !ok {
			return false
		}

		addFieldDocs(spec.Name.Name, structType)
		return false
	})
}

func addFieldDocs(typeName string, structType *ast.StructType) {
	for _, field := range structType.Fields.List {
		for _, name := range field.Names {
			docs[typeName+"."+name.Name] = field.Doc.Text()
		}
	}
}

func main() {
	names, _ := filepath.Glob("*.go")
	for _, name := range names {
		file, err := parser.ParseFile(token.NewFileSet(), name, nil, parser.ParseComments)
		if err != nil {
			log.Fatal(err)
		}

		collectDocs(file)
	}

	buffer := bytes.NewBufferString(header)
	write(buffer, "", reflect.ValueOf(config.Default()))
	if err := os.WriteFile("../../docs/config.md", append(bytes.TrimSpace(buffer.Bytes()), "\n"+footer...), 0o644); err != nil {
		log.Fatal(err)
	}

	buffer = bytes.NewBufferString(tomlHeader)
	writeTOML(buffer, "", reflect.ValueOf(config.Default()))
	if err := os.WriteFile("default.toml", buffer.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}
